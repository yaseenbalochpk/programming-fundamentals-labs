
#include <iostream>
using namespace std;

int main() {
    cout << "1. 28 / 4 - 2 = " << 28 / 4 - 2 << endl;
    cout << "2. 6 + 12 * 2 - 8 = " << 6 + 12 * 2 - 8 << endl;
    cout << "3. 4 + 8 * 2 = " << 4 + 8 * 2 << endl;
    cout << "4. 6 + 17 % 3 - 2 = " << 6 + 17 % 3 - 2 << endl;
    cout << "5. 2 + 22 * (9 - 7) = " << 2 + 22 * (9 - 7) << endl;
    cout << "6. (8 + 7) * 2 = " << (8 + 7) * 2 << endl;
    cout << "7. (16 + 7) % 2 - 1 = " << (16 + 7) % 2 - 1 << endl;
    cout << "8. 12 / (10 - 6) = " << 12 / (10 - 6) << endl;
    cout << "9. (19 - 3) * (2 + 2) / 4 = "
         << (19 - 3) * (2 + 2) / 4 << endl;

    return 0;
}
